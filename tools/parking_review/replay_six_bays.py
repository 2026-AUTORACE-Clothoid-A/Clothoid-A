#!/usr/bin/env python3
"""Audit grid selection on recorded inputs, without ROS nodes or drive publications.

Recorded entry candidates/prepare/flag are inputs; camera and YOLO are not rerun.
Fixed recorded motion cannot establish closed-loop driving success.
"""
import argparse
from collections import Counter
import json
import math
from pathlib import Path
import sqlite3
import sys
import time
import numpy as np
import yaml
from rclpy.serialization import deserialize_message
from rosidl_runtime_py.utilities import get_message

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'ros2_ws/src/clothoid_parking'))
from clothoid_parking.core import ParkingCore
from clothoid_parking.layout import LayoutParams, unique_cells
from clothoid_parking.planner import PlanParams
from clothoid_parking.bay_finder import BayParams
from clothoid_parking.exploration import ExploreParams


def run(bag):
    config = yaml.safe_load((ROOT/'ros2_ws/src/clothoid_parking/config/parking.yaml').read_text())['parking']['ros__parameters']
    def params(kind, prefix):
        return kind(**{k[len(prefix):]: v for k, v in config.items() if k.startswith(prefix)})
    lp = params(LayoutParams, 'layout.')
    lp.control_enabled = True
    core = ParkingCore(params(PlanParams, 'plan.'), params(BayParams, 'bay.'), layout=lp,
                       exploration=params(ExploreParams, 'explore.'))
    names = {'/imu', '/odom', '/scan', '/parking_prepare', '/parking_flag',
             '/parking_done', '/parking/entry_candidate'}
    counts, reasons, selected, times = Counter(), Counter(), [], []
    snapshots, events = [], []
    speed = 0.
    recorded_switches = {}
    start = None
    for db in sorted(bag.glob('*.db3')):
        with sqlite3.connect(f'file:{db}?mode=ro', uri=True) as con:
            topics = {i: (n, get_message(t)) for i, n, t in con.execute('select id,name,type from topics') if n in names}
            for tid, ts, data in con.execute('select topic_id,timestamp,data from messages order by timestamp'):
                if start is None:
                    start = ts*1e-9
                if tid not in topics:
                    continue
                name, kind = topics[tid]
                m = deserialize_message(data, kind)
                now = ts*1e-9
                stamp = (m.header.stamp.sec+m.header.stamp.nanosec*1e-9) if hasattr(m, 'header') else now
                stamp = stamp or now
                counts[name] += 1
                if name in ('/parking_prepare', '/parking_flag'):
                    if m.data and not recorded_switches.get(name, False):
                        events.append(dict(t=round(now-start, 3), event=name))
                    recorded_switches[name] = m.data
                if name == '/parking_prepare':
                    core.prepare(m.data and not core.flag)
                elif name == '/parking_flag':
                    # Record handover but do not drive the planner along a trajectory
                    # that was generated by a different controller.
                    core.flag = m.data
                elif name == '/parking_done' and m.data:
                    core.flag = False
                    core.prepare(False)
                elif not (core.preparing or core.flag):
                    continue
                elif name == '/imu':
                    core.imu(stamp, m.angular_velocity.z)
                elif name == '/odom':
                    speed = m.twist.twist.linear.x
                    core.odom(stamp, speed)
                elif name == '/parking/entry_candidate':
                    q = m.pose.pose.orientation
                    yaw = math.atan2(2*(q.w*q.z+q.x*q.y), 1-2*(q.y*q.y+q.z*q.z))
                    events.append(dict(t=round(now-start, 3), event='entry_candidate'))
                    if m.header.frame_id == 'base_link' and -.05 <= now-stamp <= .5:
                        counts['accepted_entry'] += core.observe_entry(stamp, (m.pose.pose.position.x, m.pose.pose.position.y), yaw)
                elif name == '/scan':
                    before = core.layout.last_scan
                    tick = time.perf_counter()
                    core.scan(stamp, m.ranges, m.angle_min, m.angle_increment, m.range_min, m.range_max)
                    if core.layout.last_scan == before:
                        continue
                    corridor = {}
                    original_coverage = core.layout.swept_coverage
                    def audit_corridor(points, query_time, pose):
                        result = original_coverage(points, query_time, pose)
                        layout = core.layout
                        current = set(map(tuple, unique_cells(layout.footprint(pose.x, pose.y, pose.yaw), layout.p.grid)))
                        missing, hits = [], []
                        for key in map(tuple, unique_cells(points, layout.p.grid)):
                            value = layout.cells.get(key)
                            fresh = value is not None and 0 <= query_time-value[0] <= layout.p.evidence_age
                            if fresh and value[1]:
                                hits.append(key)
                            if not fresh and key not in current:
                                missing.append(key)
                        def local(cells):
                            if not cells:
                                return []
                            delta = (np.array(cells)+.5)*layout.p.grid-np.array([pose.x,pose.y])
                            c,s = math.cos(pose.yaw),math.sin(pose.yaw)
                            return np.round(np.column_stack((c*delta[:,0]+s*delta[:,1], -s*delta[:,0]+c*delta[:,1])),3).tolist()
                        corridor.update(result=result, unknown=len(missing), occupied=len(hits),
                                        unknown_body_xy=local(missing), occupied_body_xy=local(hits))
                        return result
                    core.layout.swept_coverage = audit_corridor
                    try:
                        limit = core.exploration_limit(now)
                    finally:
                        core.layout.swept_coverage = original_coverage
                    times.append((time.perf_counter()-tick)*1000)
                    reasons[core.layout.reason] += 1
                    layout = core.layout
                    def coverage_counts(points):
                        if points is None:
                            return {'unreachable': True}
                        keys = unique_cells(points, layout.p.grid)
                        values = [layout.cells.get(tuple(k)) for k in keys]
                        unknown = np.array([v is None or stamp-v[0] > layout.p.evidence_age for v in values])
                        occupied = sum(v is not None and stamp-v[0] <= layout.p.evidence_age and v[1] for v in values)
                        result = dict(total=len(keys), unknown=int(unknown.sum()), occupied=int(occupied))
                        # Current-scan geometric obstruction, not semantic identification:
                        # nearest sampled beam returns before an unknown cell centre.
                        pts = (keys[unknown]+.5)*layout.p.grid
                        if len(pts):
                            pose = core.tracker.pose
                            origin = np.array([pose.x+core.laser_x*math.cos(pose.yaw), pose.y+core.laser_x*math.sin(pose.yaw)])
                            delta = pts-origin
                            angles = np.arctan2(delta[:,1], delta[:,0])-pose.yaw
                            angles = (angles-m.angle_min) % (2*math.pi)
                            idx = np.rint(angles/m.angle_increment).astype(int)
                            valid = (idx >= 0)&(idx < len(m.ranges))
                            r = np.array(m.ranges)[np.clip(idx, 0, len(m.ranges)-1)]
                            finite = valid & np.isfinite(r)&(r > m.range_min)&(r < m.range_max)
                            distance = np.linalg.norm(delta, axis=1)
                            result['behind_current_return'] = int(np.sum(finite & (r < distance-.08)))
                            result['invalid_current_ray'] = int(np.sum(~finite))
                        return result
                    bays = layout.bays()
                    snapshots.append(dict(t=round(now-start, 3), flag=bool(core.flag), speed=float(speed),
                        reason=layout.reason, states=list(layout.states), speed_cap=limit, corridor=corridor, exploration_reason=core.exploration.reason,
                        bays=[dict(bay=i+1, goal=coverage_counts(layout.footprint(b.x,b.y,b.entry_yaw)),
                            path=coverage_counts(layout.path(b,core.tracker.pose,core.planner.p))) for i,b in enumerate(bays)]))
                    if core.layout.selected is not None:
                        bay = core.layout.bays()[core.layout.selected]
                        pose = core.tracker.pose
                        along = ((bay.face_x-pose.x)*math.cos(bay.row_yaw)
                                 +(bay.face_y-pose.y)*math.sin(bay.row_yaw))
                        ready = bool(core.layout.turn_remaining(bay, pose, core.planner.p) >= 0.)
                        selected.append(dict(t=round(now-start, 3), bay=core.layout.selected+1,
                                             before_recorded_flag=not core.flag,
                                             turn_point_ahead=ready))
    return dict(bag=bag.name, events=events, snapshots=snapshots, counts=dict(counts), selected=selected, reasons=dict(reasons),
                milliseconds=dict(mean=float(np.mean(times)), p95=float(np.percentile(times, 95))) if times else {},
                scope='recorded entry candidates, mission gates and motion; no camera rerun or driving success claim')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('bags', nargs='+', type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    result = []
    for bag in args.bags:
        row = run(bag)
        result.append(row)
        print(json.dumps(row, ensure_ascii=False), flush=True)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2))
